// Printer-screen previews: slicer/thumbnail.js and the library's extraction.
const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const zlib = require('node:zlib');
const { Readable } = require('node:stream');
const { addThumbnails, parseToolpath, render, png, qoi, thumbnailSpecs } = require('../slicer/thumbnail');
const { Library } = require('../lib/library');

// A 20 mm hollow box, 10 layers, after a purge line that mustn't be drawn.
function boxGcode() {
  const lines = ['; HEADER_BLOCK_START', '; generated by test', '; HEADER_BLOCK_END', '', ';TYPE:Custom', 'G90', 'M83',
    'G1 X0 Y-20 Z0.3 F3000', 'G1 X200 Y-20 E20 ; purge line far from the part'];
  for (let l = 1; l <= 10; l++) {
    const z = (l * 0.2).toFixed(1);
    lines.push(';LAYER_CHANGE', `G1 Z${z}`, ';TYPE:Outer wall', 'G1 X100 Y100 F9000');
    for (const [x, y] of [[120, 100], [120, 120], [100, 120], [100, 100]]) lines.push(`G1 X${x} Y${y} E1.2`);
    lines.push('G1 X110 Y110 E-0.8 ; retract, travel');
  }
  lines.push(';TYPE:Custom', 'G1 X0 Y200 E5 ; end-of-print move', '; filament_colour = #3366FF');
  return lines.join('\n');
}

function decodePng(buf) {
  assert.equal(buf.subarray(1, 4).toString(), 'PNG');
  const w = buf.readUInt32BE(16), h = buf.readUInt32BE(20);
  const idat = [];
  for (let o = 8; o < buf.length;) {
    const len = buf.readUInt32BE(o), type = buf.toString('latin1', o + 4, o + 8);
    if (type === 'IDAT') idat.push(buf.subarray(o + 8, o + 8 + len));
    o += 12 + len;
  }
  const raw = zlib.inflateSync(Buffer.concat(idat));
  const px = Buffer.alloc(w * h * 4);
  for (let y = 0; y < h; y++) raw.copy(px, y * w * 4, y * (w * 4 + 1) + 1, (y + 1) * (w * 4 + 1)); // filter 0 rows
  return { w, h, px };
}

test('toolpath skips start/end G-code, travels and retractions', () => {
  const tp = parseToolpath(boxGcode());
  assert.equal(tp.n, 40); // 4 walls x 10 layers
  assert.deepEqual(tp.colors, [[51, 102, 255]]);
  for (let i = 0; i < tp.n; i++) {
    const x = tp.segs[i * 8], y = tp.segs[i * 8 + 1];
    assert.ok(x >= 100 && x <= 120 && y >= 100 && y <= 120, 'only the box is drawn');
  }
});

test('render fills the frame with the part, on a transparent background', () => {
  const { w, h, px } = decodePng(png(140, 110, render(parseToolpath(boxGcode()), 140, 110)));
  assert.equal(w, 140);
  assert.equal(h, 110);
  let minX = w, maxX = 0, opaque = 0, blueish = 0;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const o = (y * w + x) * 4;
      if (px[o + 3] < 128) continue;
      opaque++;
      if (px[o + 2] > px[o]) blueish++;
      minX = Math.min(minX, x); maxX = Math.max(maxX, x);
    }
  }
  assert.equal(px[3], 0, 'corner is transparent');
  assert.ok(opaque > 500, `drew something (${opaque} px)`);
  assert.ok(blueish / opaque > 0.9, 'in the filament colour');
  assert.ok(maxX - minX > w * 0.5, 'scaled up to fill the frame');
});

test('QOI output has the right header and end marker', () => {
  const img = render(parseToolpath(boxGcode()), 16, 16);
  const q = qoi(16, 16, img);
  assert.equal(q.toString('latin1', 0, 4), 'qoif');
  assert.equal(q.readUInt32BE(4), 16);
  assert.deepEqual([...q.subarray(-8)], [0, 0, 0, 0, 0, 0, 0, 1]);
});

test('thumbnail sizes come from the printer profile', () => {
  assert.deepEqual(thumbnailSpecs({ thumbnails: ['140x110'] }), [{ w: 140, h: 110, fmt: 'PNG' }]);
  assert.deepEqual(thumbnailSpecs({ thumbnails: '230x110/PNG', thumbnails_format: 'PNG' }), [{ w: 230, h: 110, fmt: 'PNG' }]);
  assert.deepEqual(thumbnailSpecs({ thumbnails: ['16x16/QOI', '640x480/PNG'] }).map((s) => s.fmt), ['QOI', 'PNG']);
  assert.deepEqual(thumbnailSpecs({ thumbnails: ['160x160/COLPIC/#30394F'], thumbnails_format: 'COLPIC' })[0].fmt, 'COLPIC');
  assert.deepEqual(thumbnailSpecs({}).map((s) => `${s.w}x${s.h}`), ['32x32', '300x300']); // Klipper default
});

test('addThumbnails embeds blocks after the header; the library extracts the largest', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'thumb-test-'));
  try {
    const file = path.join(dir, 'box.gcode');
    fs.writeFileSync(file, boxGcode());
    const preview = addThumbnails(file, { thumbnails: ['16x16/QOI', '140x110', '300x300/PNG', '320x320/COLPIC'] });
    assert.equal(preview.w, 300);
    const text = fs.readFileSync(file, 'latin1');
    assert.ok(text.indexOf('; THUMBNAIL_BLOCK_START') > text.indexOf('; HEADER_BLOCK_END'));
    assert.match(text, /^; thumbnail_QOI begin 16x16 \d+$/m);
    assert.match(text, /^; thumbnail begin 140x110 \d+$/m);
    assert.match(text, /^; thumbnail begin 300x300 \d+$/m);
    assert.doesNotMatch(text, /COLPIC begin/); // not produced; those printers also list a PNG
    const [, len, b64] = /; thumbnail begin 140x110 (\d+)\n([\s\S]*?); thumbnail end/.exec(text);
    assert.equal(b64.replace(/^; /gm, '').replace(/\n/g, '').length, Number(len));
    assert.equal(addThumbnails(file, { thumbnails: ['140x110'] }), null, 'never added twice');

    const lib = new Library(path.join(dir, 'data'));
    const item = await lib.addFromStream('box.gcode', Readable.from([fs.readFileSync(file)]));
    assert.equal(item.thumb, true);
    assert.equal(decodePng(fs.readFileSync(lib.thumbPath(item))).w, 300);
    const plain = await lib.addFromStream('plain.gcode', Readable.from([Buffer.from('G28\n')]));
    assert.equal(plain.thumb, false);
    assert.equal(lib.thumbPath(plain), null);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
